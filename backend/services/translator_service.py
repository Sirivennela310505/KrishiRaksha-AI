def normalize_lang(lang_code: str) -> str:
    if not lang_code:
        return "en"
    code = lang_code.split("-")[0].lower()
    return code if code in SUPPORTED_LANGUAGES else "en"

def get_phrase(key: str, lang: str = "en") -> str:
    normalized = normalize_lang(lang)
    if key in PHRASES:
        return PHRASES[key].get(normalized, PHRASES[key].get("en", ""))
    return ""

def translate_crop_doctor_result(data: dict, target_lang: str) -> dict:
    """
    Translates or enriches crop doctor result according to selected Indian language.
    Provides complete Telugu and Hindi symptoms, causes, remedies, precautions, and audio.
    """
    lang = normalize_lang(target_lang)
    if lang == "en":
        return data

    # 1. Identify which diagnosis key matches
    cond_lower = data.get("condition", "").lower()
    crop_lower = data.get("crop", "").lower()
    matched_key = "rice_blast"

    if "tomato" in crop_lower or "blight" in cond_lower:
        matched_key = "tomato_blight"
    elif "cotton" in crop_lower or "bollworm" in cond_lower:
        matched_key = "cotton_bollworm"
    elif "wheat" in crop_lower or "rust" in cond_lower:
        matched_key = "wheat_rust"
    elif "chilli" in crop_lower or "curl" in cond_lower:
        matched_key = "chilli_leaf_curl"
    elif "rice" in crop_lower or "paddy" in crop_lower or "blast" in cond_lower:
        matched_key = "rice_blast"

    # 2. Pull localized content if available
    if matched_key in LOCALIZED_DIAGNOSES and lang in LOCALIZED_DIAGNOSES[matched_key]:
        loc = LOCALIZED_DIAGNOSES[matched_key][lang]
        data["condition"] = loc["condition"]
        data["crop"] = loc["crop"]
        data["pathogen_type"] = loc["pathogen_type"]
        data["symptoms"] = loc["symptoms"]
        data["causes"] = loc["causes"]
        data["organic_remedies"] = loc["organic_remedies"]
        data["chemical_remedies"] = loc["chemical_remedies"]
        data["precautions"] = loc["precautions"]
        data["expert_consultation_trigger"] = loc["expert_consultation_trigger"]
        data["audio_narrative"] = loc["audio_narrative"]
    else:
        # Generic crop translation fallback
        crop_translations = {
            "paddy": {"hi": "धान / चावल", "te": "వరి ధాన్యం", "ta": "நெல்", "kn": "ಭತ್ತ", "ml": "നെല്ല്"},
            "tomato": {"hi": "टमाटर", "te": "టమోటా", "ta": "தக்காளி", "kn": "ಟೊಮೆಟೊ", "ml": "തക്കാളി"},
            "cotton": {"hi": "कपास", "te": "ప్రత్తి (పత్తి)", "ta": "பருத்தி", "kn": "ಹತ್ತಿ", "ml": "പരുത്തി"},
            "wheat": {"hi": "गेहूं", "te": "గోధుమలు", "ta": "கோதுமை", "kn": "ಗೋಧಿ", "ml": "గోതമ്പ്"},
            "chilli": {"hi": "मिर्च", "te": "మిరపకాయ", "ta": "மிளகாய்", "kn": "ಮೆಣಸಿನಕಾಯಿ", "ml": "മുളക്"}
        }
        for k, v in crop_translations.items():
            if k in crop_lower:
                data["crop"] = v.get(lang, data.get("crop"))
                break

    # Add translated disclaimer
    data["disclaimer"] = get_phrase("disclaimer", lang)

    return data
